import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const base = path.resolve('dist');
const file = (p) => fs.readFileSync(path.join(base, p), 'utf8');
const homepage = file('index.html');
assert.match(homepage, /<main id="pre-rendered-content"/, 'homepage must serve visible static content');
assert.match(homepage, /<h1>/, 'homepage requires a visible H1');
assert.match(homepage, /https:\/\/www\.chronolyteai\.site\//, 'canonical site URL');
assert.doesNotMatch(homepage, /chronolyte\.com/, 'old domain must not be emitted');
assert.doesNotMatch(homepage, /"aggregateRating"/, 'unverified rating must not be emitted');
assert.doesNotMatch(homepage, /left:-9999px/, 'hidden crawler text is not allowed');
assert.match(file('services/index.html'), /<h1>/);
const robots = file('robots.txt');
assert.match(robots, /User-agent: OAI-SearchBot/);
assert.match(robots, /User-agent: Claude-SearchBot/);
assert.match(robots, /Sitemap: https:\/\/www\.chronolyteai\.site\/sitemap\.xml/);
assert.match(file('sitemap.xml'), /https:\/\/www\.chronolyteai\.site\/services/);
assert.match(file('llms.txt'), /https:\/\/www\.chronolyteai\.site\/contact/);
console.log('[seo] verified canonical domain, readable HTML, honest schema and crawler discovery');
